class Sniffer:
    
    # Packet dumper class (subclass of PacketFilter)
    class PacketDumper(PacketFilter):
        def __init__(self, logfile, deferredDump = True):
            PacketFilter.__init__(self)
            
            self.logfile = logfile
            self.deferredDump = deferredDump
            self.prevDumpedPacket = None
    
        def flush(self):
            for p in self.getList():
                self.__dumpPkt(p)
            
        def close(self):
            self.prevDumpedPacket = None
            self.logfile.close()
        
        def wait(self):
            return True
    
        def __dumpPkt(self, packetDict):
            
            # pkt time is the packet's rx end time as defined for tests;
            # for coherence with logging generated by GUI, which follows the standard's definition,
            # pkt time must be the packet's rx start time;
            # this requires making a copy of the packetDict to avoid modifying the referenced object
            pktDict = copy.deepcopy(packetDict)
            pktDict['phyTime'] = TimeConst.incr10us(pktDict['phyTime'], -(pktDict['packet'].calcTxDuration(pktDict['scheme'])))
            
            txt = pktDict['sysTime'].strftime("%H:%M:%S.%f")[:-5]
            txt += "," + str(pktDict['phyTime']) + ","
            if self.prevDumpedPacket is not None:
                txt += str(TimeConst.pkt10usDiff(self.prevDumpedPacket, pktDict))
            else:
                txt += str(pktDict['phyTime'])
            txt += "," + ",".join(pktDict['packet'].getFieldsToStrings())
            
            txt += "," + str(pktDict['scheme'] & 0xF)
            txt += "," + ",".join([str(pktDict[k]) for k in ['level', 'snr', 'rxQ']])
            txt += "," + str((pktDict['scheme'] >> 4) & 0xF)
            
            self.logfile.write(txt + ",\n")
            
            self.prevDumpedPacket = pktDict
        
        def checkPacket(self, packetDict):
            if self.deferredDump:
                return True
            else:
                self.__dumpPkt(packetDict)
                return False
    
    InitFailure = True
    IndicationThreadRunning = False
    QueueThreadRunning = False
    IndicationQueue = deque()
    
    def __init__(self, port, testname, baud=57600):
        try:
            self.serialcom = serial.Serial(port, baud, timeout=1)
        except:
            try:
                #print ("OpenCom retry")
                time.sleep(1) 
                self.serialcom = serial.Serial(port, baud, timeout=1)
            except:
                time.sleep(0.5) # fake init time
                #print ("OpenCom fail")
                return
        self.seriallock = Lock()
        self.sci = SciInterface(self.serialcom, self.seriallock)
        self.eci = EciInterface(self.serialcom, self.seriallock)
        prod = self.sci.GetPib(SpecPibs.AppProductId)
        if (len(prod) != 2):
            print(("wrong PRODUCT_ID, prod = " + str(prod)))
            return
        self.ProductID = (prod[0] << 8) + prod[1]
		
        if self.ProductID == Vendor.ProductId.SN_EMB:
            #use 0x0000 pib to access EUI48
            self.eui48 = self.GetPib(0x0000, iface = "ECI")
            #print "ECI GetPib EUI48 ok"
        else:
            self.eui48 = self.GetPib(SpecPibs.macEUI48)
            #print "SCI GetPib EUI48 ok"
			
        primeConfPHY = 1
        self.sci.SetPib(CommonVendSpecPibs.primeConfig, [primeConfPHY])   
        time.sleep(1)
        prime_conf = self.sci.GetPib(CommonVendSpecPibs.primeConfig)
        if (prime_conf != [primeConfPHY]):
            print(("wrong config, PRIMECONFIG = " + str(prime_conf)))
            return
        # flush previous PHY_DATAindications
        for _ in range (0, 64):
            self.eci.PHY_DATAindication1_4()
        
        # List of instances of PacketFilter class
        self.pktFilters = []
        
        # PacketFilter collecting all packets (wrong CRC/HCS comprised), is used
        # to dump CVS file at the end of the test
        f = self.PacketDumper(open(os.path.join(config.ResultsFolder, time.strftime("%Y_%m_%d-%H_%M_%S_") + testname + ".csv"), "w"), 
                              config.snifferPacketDumpDeferred)
        f.acceptWrongCrc()
        f.disable()
        self.addPacketFilter(f)
        
        self.InitFailure = False
        self.snaToFollow = None
        
    def __del__(self):
        if not self.InitFailure:
            #self.Stop() already called by test
            
            del self.eci
            del self.sci
            self.serialcom.close()
            del self.serialcom
            
            for f in self.pktFilters:
                if isinstance(f, self.PacketDumper):
                    f.close()
                if not isinstance(f, FramingMonitor):
                    self.removePacketFilter(f) # Removal of f from memory left to Python's garbage collector
            if self.pktFilters != []:
                # Framing monitor left
                self.removePacketFilter(self.pktFilters[0])
        
    def Start(self):
        if not self.IndicationThreadRunning:
            self.IndicationThreadRunning = True
            self.IndicationThread = Thread(target=self.IndicationThreadFunc, args=[])
            self.IndicationThread.start()
        if not self.QueueThreadRunning:
            self.QueueThreadRunning = True
            self.QueueThread = Thread(target=self.QueueThreadFunc, args=[])
            self.QueueThread.start()
            
        [f for f in self.pktFilters if isinstance(f, self.PacketDumper)][0].enable()

    def Stop(self):
        if self.QueueThreadRunning:
            self.QueueThreadRunning = False
            self.QueueThread.join()
            del self.QueueThread
        if self.IndicationThreadRunning:
            self.IndicationThreadRunning = False
            self.IndicationThread.join()
            del self.IndicationThread
            
        f = [f for f in self.pktFilters if isinstance(f, self.PacketDumper)][0]
        f.flush()
        f.disable()

    def DeviceType(self, productID):
        if productID == Vendor.ProductId.SN_EMB:
            return "SN EMB"
        if productID == Vendor.ProductId.SN_STM32:
            return "SN STM32"
        if productID == Vendor.ProductId.SN_STCOMET:
            return "SN STCOMET 1.4 (lib Binary)"
        if productID == Vendor.ProductId.SN_STCOMET_LIBCOMPILED:
            return "SN STCOMET 1.4 (lib Compiled)"
        if productID == Vendor.ProductId.SN_STARCOM_LIBCOMPILED:
            return "SN ST8500 1.4"
        return "UNKNOWN"

    def NodeInfo(self):
        fwver = self.GetPib(SpecPibs.AppFwVersion)
        if ((len(fwver) != 16) and (len(self.eui48) != 6 )):
            #print "error reading node info"
            return "error reading node info"
        txt = ":".join("{:02X}".format(c) for c in self.eui48) + ", "
        txt += self.DeviceType(self.ProductID) + " "
        txt += "".join(chr(c) for c in fwver).strip("\0")
        return txt

    def GetEciPib (self, pib, timeout=10):
        endtime = time.time() + timeout
        if self.eci.MAC_MLME_GETrequest(pib) == 0:
            #print "ECI MAC_MLME_GETrequest ok"
            while True:
                ec, _, _, value = self.eci.MAC_MLME_GETconfirm()
                if ec == 0:
                    #print "ECI MAC_MLME_GETconfirm ok"
                    break
                if time.time() > endtime:
                    #print "ECI GetEciPib timeout"
                    return []
                time.sleep(0.015)
            return value
        return []

    def GetPib(self, pib, iface="SCI", endianness=0):
        if iface == "SCI":
            arr = self.sci.GetPib(pib)
        else:
            arr = self.GetEciPib(pib)

        if len(arr) == 1:
            return arr[0] # cast to uint8_t
        elif len(arr) == 2:
            return (arr[0] << 8) + arr[1]  # cast to uint16_t
        elif len(arr) == 4:
            return (arr[0] << 24) + (arr[1] << 16) + (arr[2] << 8) + arr[3]  # cast to uint32_t
        else:
            return arr

    def QueueThreadFunc(self):
        while self.QueueThreadRunning:
            if len(self.IndicationQueue) > 0:
                pctime, lev, modulation, phytime, snr, rq, raw = self.IndicationQueue.popleft()
                
                packet = Packet(raw, self.snaToFollow)
                try:
                    if self.snaToFollow is None and packet.bpdu().sid == Addresses.LSID_BASENODE:
                        self.snaToFollow = packet.bpdu().sna
                except:
                    pass
                
                if ((self.ProductID == Vendor.ProductId.SN_STCOMET) or (self.ProductID == Vendor.ProductId.SN_STCOMET_LIBCOMPILED) or (self.ProductID == Vendor.ProductId.SN_STARCOM_LIBCOMPILED)):
                    # convert from start of RX time to end of RX time
                    phytime = TimeConst.incr10us(phytime, packet.calcTxDuration(modulation))
                
                self.filterPacket(packet, lev, modulation, pctime, phytime, snr, rq)
                
            else:
                time.sleep(0.1)

    def IndicationThreadFunc(self):
        while self.IndicationThreadRunning:
            ec, lev, modulation, tim, snr, rq, di = self.eci.PHY_DATAindication1_4()
            if ec == 0:
                self.IndicationQueue.append((datetime.now(), lev, modulation, tim, snr, rq, di))
            elif ec == 0x99:
                time.sleep(0.015) # no indications, we can sleep to save CPU usage
            else:
                time.sleep(1)
                self.serialcom.close() # error, try to close and reopen serial port
                time.sleep(1)
                self.serialcom.open()
        time.sleep(0.25)
    
    # Add a one or more PacketFilter instances to the set
    # Each 'pktFilter' must be an instance of 'PacketFilter' class 
    # and shall not be already present in the set.
    # Returns a list of True/False to tell the insertion oucome of
    # each filter 
    def addPacketFilter(self, *pktFilters):
        retVal = []
        
        for f in pktFilters:
            if not isinstance(f, PacketFilter):
                retVal += [False]
            else:
                if isinstance(f, FramingMonitor):
                    if [f1 for f1 in self.pktFilters if isinstance(f1, FramingMonitor)] != []:
                        retVal += [False]
                        continue
                
                if f not in self.pktFilters:
                    self.pktFilters += [f]
                    retVal += [True]
                else:
                    retVal += [False]
        
        if retVal == []:
            retVal = [False]
        
        return retVal
    
    # Remove a one or more PacketFilter instances previously added to the set
    # Returns a list of True/False to tell the removal oucome of
    # each filter 
    def removePacketFilter(self, *pktFilters):
        retVal = []
        
        for f in pktFilters:
            # Special removal is for FramingMonitor
            if isinstance(f, FramingMonitor):
                if [f1 for f1 in self.pktFilters if isinstance(f1, CfpPacketFilter) or isinstance(f1, ScpPacketFilter)] != []:
                    # Cannot remove framing monitor, because either scp or cfp are still alive
                    retVal += [False]
                    continue
    
            try:
                self.pktFilters.remove(f)
                retVal += [True]
            except ValueError:
                retVal += [False]
            
        if retVal == []:
            retVal = [False]
        
        return retVal
    
    # Add a Framing Monitor
    def addFramingMonitor(self):
        self.addPacketFilter(FramingMonitor())
            # Note: here the removal of FramingMonitor() in case another one has been
            # already added to the set of active filters is left to Python's
            # garbage collector mechanism 
        return [f for f in self.pktFilters if isinstance(f, FramingMonitor)][0]
    
    # Add the CfpPacketFilter and return it
    def addCfpPacketFilter(self):
        for f in self.pktFilters:
            if isinstance(f, CfpPacketFilter):
                return f
        f = CfpPacketFilter(self.addFramingMonitor())
        self.addPacketFilter(f)
        return f
    
    # Add the ScpPacketFilter and return it
    def addScpPacketFilter(self):
        for f in self.pktFilters:
            if isinstance(f, ScpPacketFilter):
                return f
        f = ScpPacketFilter(self.addFramingMonitor())
        self.addPacketFilter(f)
        return f
                
    # Add the PacketFilter instance collecting BCN / BCN_S and return it.
    # If optional parameter 'sid' is specified and valid value is given (>=0 and < 0xFF), 
    # only BCN / BCN_S from the switch with that SID will be collected
    # If invalid 'sid' value is provided, no filter is created and None is returned 
    def addBcnPacketFilter(self, sid = None):
        if sid == None:
            f = PacketFilter(lambda pktDict: pktDict['packet'].isBpdu())
        elif sid >= Addresses.LSID_BASENODE and sid < Addresses.LSID_UNASSIGNED:
            f = PacketFilter(lambda pktDict: pktDict['packet'].isBpdu() and pktDict['packet'].bpdu().sid == sid)
        else:
            f = None
        if f is not None:
            self.addPacketFilter(f)
        return f
    
    # Add the PacketFilter instance collecting PNPDUs and return it.
    # If optional parameter 'pna' is specified, only PNPDUs from that PNA will be collected
    def addPnpduPacketFilter(self, pna = None):
        if pna == None:
            f = PacketFilter(lambda pktDict: pktDict['packet'].isPnpdu())
        else:
            f = PacketFilter(lambda pktDict: pktDict['packet'].isPnpdu() and pktDict['packet'].pnpdu().pna == pna)
        self.addPacketFilter(f)
        return f
    
    # Add a PacketFilter instance collecting data GPDUs and return it
    def addDataPacketFilter(self):
        f = PacketFilter(lambda pktDict: pktDict['packet'].isGpdu() and not pktDict['packet'].isControl())
        self.addPacketFilter(f)
        return f
    
    # Add a PacketFilter instance collecting control GPDUs and return it
    def addCtrlPacketFilter(self, ctype = None):
        f = PacketFilter(lambda pktDict: pktDict['packet'].isGpdu() and pktDict['packet'].isControl() and
                         (ctype == None or pktDict['packet'].phdr().ctype == ctype))
        self.addPacketFilter(f)
        return f
    
    # Add a PacketFilter instance collecting all PDUs and return it
    def addAllPacketFilter(self):
        f = PacketFilter(lambda pktDict: True)
        self.addPacketFilter(f)
        return f
        
    def filterPacket(self, packet, lev, sch, pctime, tim, snr, rq):
        pktDict = {
            'packet'  : packet,
            'level'   : lev,
            'scheme'  : sch,
            'phyTime' : tim,
            'sysTime' : pctime,
            'snr'     : snr,
            'rxQ'     : rq }
        
        for f in self.pktFilters:
            f.collectPacketDict(pktDict)
